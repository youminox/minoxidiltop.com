export const TOP_NATIONAL_BARBERIAS: PeruBarberiaSummary[] = PERU_BARBERIAS.filter(
  (b) => b.isNationalTop
).slice(0, 6);

export function getBarberiasByLocation(query?: string): PeruBarberiaSummary[] {
  if (!query) return TOP_NATIONAL_BARBERIAS.slice(0, 4);
  const q = query
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");

  const exactDistrict = PERU_BARBERIAS.filter((b) => {
    const d = b.district
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "");
    return d.includes(q) || q.includes(d);
  });
  if (exactDistrict.length >= 2) return exactDistrict.slice(0, 4);

  const exactCity = PERU_BARBERIAS.filter((b) => {
    const c = b.city
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "");
    return c.includes(q) || q.includes(c);
  });
  if (exactCity.length > 0) {
    const merged = [...exactDistrict, ...exactCity.filter((x) => !exactDistrict.includes(x))];
    return merged.slice(0, 4);
  }

  return [...exactDistrict, ...TOP_NATIONAL_BARBERIAS].slice(0, 4);
}
